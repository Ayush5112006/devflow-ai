function daysAgo(n: number): string {
  const d = new Date();
  d.setDate(d.getDate() - n);
  return d.toISOString().split('T')[0];
}

function daysFrom(n: number): string {
  const d = new Date();
  d.setDate(d.getDate() + n);
  return d.toISOString().split('T')[0];
}

function seeded(seed: number, min: number, max: number): number {
  // deterministic pseudo-random so data doesn't flicker on re-renders
  const x = Math.sin(seed) * 10000;
  const r = x - Math.floor(x);
  return +(min + r * (max - min)).toFixed(2);
}

function generateSensorReadings(
  baseTemp: number,
  baseVibration: number,
  basePD: number,
  baseOilQuality: number,
  assetSeed: number,
  days = 30,
): SensorReading[] {
  const readings: SensorReading[] = [];
  for (let i = days; i >= 0; i--) {
    const d = new Date();
    d.setDate(d.getDate() - i);
    const s = assetSeed + i;
    readings.push({
      timestamp: d.toISOString(),
      temperature_c: +(baseTemp + seeded(s * 1.1, -4, 6)).toFixed(1),
      vibration_mm_s: +(baseVibration + seeded(s * 2.3, -0.3, 0.5)).toFixed(2),
      partial_discharge_mv: +(basePD + seeded(s * 3.7, -30, 50)).toFixed(1),
      oil_quality_index: +(baseOilQuality + seeded(s * 4.1, -5, 5)).toFixed(1),
      load_percent: +(55 + seeded(s * 5.9, -20, 30)).toFixed(1),
    });
  }
  return readings;
}

function shapFactors(
  temp: number,
  pd: number,
  vib: number,
  weather: number,
  age: number,
): ShapFactor[] {
  return [
    { name: 'Temperature', value: temp },
    { name: 'Partial Discharge', value: pd },
    { name: 'Vibration', value: vib },
    { name: 'Weather Risk', value: weather },
    { name: 'Asset Age', value: age },
  ].sort((a, b) => b.value - a.value);
}

function riskLevelFromScore(score: number): RiskLevel {
  if (score >= 85) return 'critical';
  if (score >= 70) return 'high';
  if (score >= 45) return 'medium';
  return 'low';
}

